"""
Do the engine's validator and the CP-SAT constraint model agree on what is legal?

The gate in optimality.py proves the model can express one valid plan per
scenario. It says nothing about the rest of the space, so an INFEASIBLE verdict
could still rest on a constraint that is too strict somewhere the gate never
looked.

This probes the space directly. Random schedules are generated by perturbing the
published plans, and both checkers are asked whether each one is legal. Agreement
across many random schedules is evidence that the model encodes the same rules;
any disagreement names a bug in one of them and says which way it leans.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

import os, random, sys, collections
sys.path.insert(0, str(Path(__file__).resolve().parent))
import api, core, rules as R
from ortools.sat.python import cp_model
import optimality as O
import audit as A

random.seed(20261029)
engine = api.Engine()
N = int(sys.argv[1]) if len(sys.argv) > 1 else 400

cases = []
for inst in ("USYD", "UTS"):
    for key in engine.plans.get(inst, {}):
        cases.append((inst, key))

agree = disagree = skipped = 0
both_ok = both_bad = 0
model_stricter = engine_stricter = 0
examples = collections.defaultdict(list)
reasons = {}

for n in range(N):
    inst, key = random.choice(cases)
    plan = engine.plans[inst][key]
    rules = engine.rules[inst]
    data = engine._dataset_for(inst, plan)
    prereqs, coreqs, dependents = engine._graph(inst, plan)
    sched = engine._schedule_for(inst, plan)
    named = [c for v in sched.values() for c in v if not R.is_placeholder(c)]
    if not named:
        skipped += 1; continue

    failed = random.choice(named)
    horizon = max(sched) + 1 + random.choice([0, 2, 4])

    # a random perturbation: move a handful of units to random legal-ish spots
    trial = {i: [c for c in v] for i, v in sched.items()}
    pos = {c: i for i, v in trial.items() for c in v}
    # Small, plausible perturbations rather than wholesale shuffles. A random
    # schedule is almost always illegal, which tests agreement only on obviously
    # broken plans; the verdicts that matter live near the legal boundary.
    movers = random.sample(named, min(len(named), random.randint(1, 2)))
    for mv in movers:
        src = pos[mv]
        legal = [i for i in range(horizon) if rules.offered_in(mv, i, data)]
        near = [i for i in legal if abs(i - src) <= 4] or legal or [src]
        dst = random.choice(near)
        trial[src] = [c for c in trial[src] if c != mv]
        trial.setdefault(dst, []).append(mv)
        pos[mv] = dst
    # mark the failure, as a repair scenario would
    fsrc = pos[failed]
    trial[fsrc] = [c for c in trial[fsrc] if c != failed]
    later = [i for i in range(fsrc + 1, horizon) if rules.offered_in(failed, i, data)]
    newpos = random.choice(later) if later else fsrc + 1
    trial.setdefault(newpos, []).append(failed)
    pos[failed] = newpos
    trial.setdefault(fsrc, []).append(f"{R.FAILED_PREFIX}{failed}")
    horizon = max(horizon, max(trial) + 1)

    # engine's verdict
    eng_clean = not A.audit(rules, trial, data, R, core)

    # model's verdict on the same assignment
    built = O.build(engine, core, R, inst, key, failed, horizon, None)
    if built is None:
        skipped += 1; continue
    m, mpos, last, units, _ = built
    feasible = True
    for u in units:
        if u.startswith("__ELECTIVE"):
            continue
        if u not in pos:
            feasible = False; break
        if pos[u] >= horizon:
            feasible = False; break
        m.Add(mpos[u] == pos[u])
    if not feasible:
        skipped += 1; continue
    s = cp_model.CpSolver(); s.parameters.max_time_in_seconds = 5
    st = s.Solve(m)
    if st == cp_model.UNKNOWN:
        skipped += 1; continue
    mod_clean = st in (cp_model.OPTIMAL, cp_model.FEASIBLE)

    if eng_clean == mod_clean:
        agree += 1
        both_ok += eng_clean
        both_bad += not eng_clean
    else:
        disagree += 1
        if eng_clean and not mod_clean:
            model_stricter += 1
            if len(examples["model stricter"]) < 4:
                examples["model stricter"].append((inst, key[:40], failed))
        else:
            engine_stricter += 1
            # Record WHICH rule the engine objected to. A disagreement is only
            # informative once it is attributed: a rule the model does not
            # encode at all is a scope gap, not a contradiction.
            for line in A.audit(rules, trial, data, R, core):
                kind = ("load" if "ceiling" in line else
                        "availability" if "not offered" in line else
                        "threshold" if "beforehand" in line else
                        "corequisite" if "at or before" in line else
                        "exclusion" if "combined" in line else
                        "retake floor" if "at or before the attempt" in line else
                        "prerequisite")
                reasons[kind] = reasons.get(kind, 0) + 1
            if len(examples["engine stricter"]) < 4:
                examples["engine stricter"].append((inst, key[:40], failed))

print(f"random schedules compared: {agree + disagree}   (skipped {skipped})")
print(f"  agree                      : {agree}"
      f"  ({100*agree/(agree+disagree) if agree+disagree else 0:.1f}%)")
print(f"     both say legal          : {both_ok}")
print(f"     both say illegal        : {both_bad}")
print(f"  disagree                   : {disagree}")
print(f"     model stricter (inflates 'optimal'): {model_stricter}")
print(f"     engine stricter                    : {engine_stricter}")
if reasons:
    print(f"  rules the engine objected to, where the model did not: {reasons}")
for k, v in examples.items():
    print(f"  e.g. {k}: {v}")
